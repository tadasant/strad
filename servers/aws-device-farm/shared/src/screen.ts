/**
 * The accessibility hierarchy, turned into something an agent can assert on.
 *
 * THIS IS THE ASSERTION CHANNEL, and it is the answer to "can a device farm
 * tell me the app is working". A screenshot proves a screen was drawn; it does
 * not let a caller say `label == "0:42"`. The XCUITest page source does: every
 * element the app exposes to accessibility, with its label, its value, whether
 * it is enabled and where it is. Reading it twice a second apart is how "the
 * timer line doesn't move" becomes a test rather than an opinion.
 *
 * WHY A SCANNER AND NOT AN XML PARSER. The document is machine-generated by one
 * producer, it is attributes-only — no text nodes, no CDATA, no namespaces —
 * and a phone's hierarchy runs to hundreds of kilobytes. A dependency-free scan
 * over the open tags is the whole job, and it cannot fail on a document the
 * parser would have rejected for a reason nobody can act on.
 *
 * COORDINATES ARE POINTS, NOT PIXELS. The `x`/`y`/`width`/`height` here are the
 * logical coordinates XCUITest reports, and they are what `tap_screen` and
 * `swipe_screen` take. A screenshot of the same phone is two or three times
 * larger in every direction, so a coordinate read off an IMAGE lands somewhere
 * else entirely — usually near the top-left of what was aimed at. Every tool
 * description that takes a coordinate says so.
 */

export interface ScreenRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface ScreenElement {
  /** `Button`, `StaticText`, `TextField` — the `XCUIElementType` prefix removed. */
  type: string;
  label?: string;
  name?: string;
  value?: string;
  enabled?: boolean;
  visible?: boolean;
  rect?: ScreenRect;
  /** Where to tap to hit this element. Present whenever the rect is. */
  center?: { x: number; y: number };
}

export interface ParseScreenOptions {
  /** Case-insensitive substring matched against label, name, value and type. */
  query?: string;
  /** Return every node, including the layout scaffolding. Default: false. */
  include_all?: boolean;
  limit: number;
}

export interface ParsedScreen {
  elements: ScreenElement[];
  /** How many elements matched before the limit was applied. */
  matched: number;
  /** Every node in the hierarchy, matched or not. */
  total: number;
  truncated: boolean;
}

/**
 * The types worth returning by default even when they carry no text.
 *
 * Everything else has to say something — a label, a name or a value — to make
 * the cut. A phone's hierarchy is mostly `Other` and `Window` nodes wrapping
 * the handful of elements a person can actually see or touch, and returning
 * them all is how a `read_screen` costs ten thousand tokens to say "the Play
 * button is enabled".
 */
const ALWAYS_KEEP = new Set([
  "Button",
  "Cell",
  "CheckBox",
  "Link",
  "PickerWheel",
  "SearchField",
  "SecureTextField",
  "Slider",
  "StaticText",
  "Switch",
  "TextField",
  "TextView",
]);

const XML_ENTITIES: Record<string, string> = {
  "&amp;": "&",
  "&lt;": "<",
  "&gt;": ">",
  "&quot;": '"',
  "&apos;": "'",
  "&#10;": "\n",
  "&#9;": "\t",
};

function unescapeXml(value: string): string {
  return value.replace(/&(?:amp|lt|gt|quot|apos|#10|#9);/g, (m) => XML_ENTITIES[m] ?? m);
}

function num(value: string | undefined): number | undefined {
  if (value === undefined) return undefined;
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : undefined;
}

function bool(value: string | undefined): boolean | undefined {
  if (value === "true") return true;
  if (value === "false") return false;
  return undefined;
}

/** Every open tag in the document, with its attributes. Closing tags are skipped. */
function* tags(xml: string): Generator<{ tag: string; attrs: Record<string, string> }> {
  const tagRe = /<([A-Za-z_][\w.-]*)((?:\s+[\w:.-]+="[^"]*")*)\s*\/?>/g;
  const attrRe = /([\w:.-]+)="([^"]*)"/g;
  for (const match of xml.matchAll(tagRe)) {
    const attrs: Record<string, string> = {};
    for (const a of (match[2] ?? "").matchAll(attrRe)) {
      attrs[a[1]!] = unescapeXml(a[2]!);
    }
    yield { tag: match[1]!, attrs };
  }
}

export function parseScreen(xml: string, options: ParseScreenOptions): ParsedScreen {
  const query = options.query?.trim().toLowerCase();
  const elements: ScreenElement[] = [];
  let total = 0;
  let matched = 0;

  for (const { tag, attrs } of tags(xml)) {
    // `AppiumAXDocument` is the document wrapper, not an element on screen.
    if (tag === "AppiumAXDocument") continue;
    total += 1;

    const type = (attrs.type ?? tag).replace(/^XCUIElementType/, "");
    const label = attrs.label || undefined;
    const name = attrs.name || undefined;
    const value = attrs.value || undefined;
    const visible = bool(attrs.visible);

    if (!options.include_all) {
      // Invisible nodes are skipped before anything else: an iOS hierarchy
      // carries whole off-screen view controllers, and a label found there is
      // the most convincing wrong answer this tool can give.
      if (visible === false) continue;
      if (!ALWAYS_KEEP.has(type) && !label && !name && !value) continue;
    }

    if (query) {
      const hay = `${type} ${label ?? ""} ${name ?? ""} ${value ?? ""}`.toLowerCase();
      if (!hay.includes(query)) continue;
    }

    matched += 1;
    if (elements.length >= options.limit) continue;

    const x = num(attrs.x);
    const y = num(attrs.y);
    const width = num(attrs.width);
    const height = num(attrs.height);
    const rect =
      x !== undefined && y !== undefined && width !== undefined && height !== undefined
        ? { x, y, width, height }
        : undefined;

    elements.push({
      type,
      ...(label ? { label } : {}),
      ...(name ? { name } : {}),
      ...(value ? { value } : {}),
      ...(bool(attrs.enabled) === undefined ? {} : { enabled: bool(attrs.enabled) }),
      ...(visible === undefined ? {} : { visible }),
      ...(rect
        ? {
            rect,
            center: {
              x: Math.round(rect.x + rect.width / 2),
              y: Math.round(rect.y + rect.height / 2),
            },
          }
        : {}),
    });
  }

  return {
    elements,
    matched,
    total,
    truncated: matched > elements.length,
  };
}
