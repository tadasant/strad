/**
 * Every key in this file is generated by the test and thrown away with it.
 * The fake strad records what it was sent; nothing reaches a real store.
 */
const CUSTODY_KEY = "custody-key-0123456789abcdef0123456789abcd";

const sshKeygen = ["/usr/bin/ssh-keygen", "/opt/homebrew/bin/ssh-keygen"].find(
  (p) => existsSync(p),
);

/** What ssh-keygen derives from a private key: the public line and the fingerprint. */
function viaSshKeygen(privateKey: string): {
  publicKey: string;
  fingerprint: string;
} {
  const dir = mkdtempSync(join(tmpdir(), "hostd-keygen-"));
  try {
    const file = join(dir, "id");
    writeFileSync(file, privateKey, { mode: 0o600 });
    const publicKey = execFileSync(sshKeygen!, ["-y", "-f", file], {
      encoding: "utf8",
    }).trim();
    const fingerprint = execFileSync(sshKeygen!, ["-lf", file], {
      encoding: "utf8",
    }).split(" ")[1]!;
    return { publicKey, fingerprint };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

describe("mintKeypair", () => {
  it("writes an unencrypted OpenSSH ed25519 key and its one-line public half", () => {
    const k = mintKeypair("ed25519", "strad ssh-example-staging");
    expect(k.privateKey).toMatch(
      /^-----BEGIN OPENSSH PRIVATE KEY-----\n[A-Za-z0-9+/=\n]+\n-----END OPENSSH PRIVATE KEY-----\n$/,
    );
    expect(k.publicKey).toMatch(
      /^ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAI[A-Za-z0-9+/]{43} strad ssh-example-staging$/,
    );
    expect(k.fingerprint).toMatch(/^SHA256:[A-Za-z0-9+/]{43}$/);
    expect(shapeOf(k.privateKey).kind).toBe("pem");
    // Fresh every call.
    expect(mintKeypair("ed25519", "x").publicKey).not.toBe(
      mintKeypair("ed25519", "x").publicKey,
    );
  });

  it.skipIf(!sshKeygen)(
    "is a key ssh-keygen reads, with the same public key and fingerprint",
    () => {
      const k = mintKeypair("ed25519", "strad ssh-example-staging");
      expect(viaSshKeygen(k.privateKey)).toEqual({
        publicKey: k.publicKey,
        fingerprint: k.fingerprint,
      });
    },
  );

  it("filters the private key and never the public one", () => {
    const k = mintKeypair("ed25519", "strad ssh-example-staging");
    const vault = new Vault({ handleTtlMs: 60_000 });
    const { handle } = vault.hold("g", k.privateKey, { source: "t" });
    expect(vault.scan([k.privateKey])).toEqual([handle]);
    const bodyLine = k.privateKey.split("\n")[2]!;
    expect(vault.scan([`cat id: ${bodyLine}`])).toEqual([handle]);
    // The public half goes into a tool result, an authorized_keys file and a
    // CI variable: it must never trip the filter that guards the private one.
    expect(vault.scan([k.publicKey, k.fingerprint])).toEqual([]);
    for (const n of needlesFor(k.privateKey))
      expect(k.publicKey.includes(n)).toBe(false);
  });

  it("refuses a comment that could break an authorized_keys line", () => {
    for (const bad of [
      "",
      " lead",
      "trail ",
      "a\nb",
      "a\tb",
      "é",
      "x".repeat(121),
    ])
      expect(KEY_COMMENT.test(bad)).toBe(false);
    for (const good of ["a", "strad ssh-example", "x".repeat(120)])
      expect(KEY_COMMENT.test(good)).toBe(true);
    expect(() => mintKeypair("ed25519", "a\nb")).toThrow(/comment/);
  });
});

describe("generate_keypair, through the daemon", () => {
  let daemon: RunningDaemon;
  let strad: Server;
  let stateDir: string;
  const deposits: { url: string; authorization?: string; value: string }[] = [];

  type C = Awaited<ReturnType<typeof connect>>;
  let custody: C;
  let shell: C;
  const grants: Record<string, string> = {};
  const call = (
    c: C,
    server: string,
    name: string,
    args: Record<string, unknown> = {},
  ) => c.callTool({ name, arguments: { grant_id: grants[server], ...args } });
  const shellWorks = async () =>
    !(await call(shell, "shell", "run_command", { command: "echo hi" }))
      .isError;

  beforeAll(async () => {
    strad = createServer((req, res) => {
      let body = "";
      req.on("data", (c) => (body += c));
      req.on("end", () => {
        const value = (JSON.parse(body || "{}") as { value: string }).value;
        deposits.push({
          url: req.url ?? "",
          authorization: req.headers.authorization,
          value,
        });
        const [, , , slug, variable] = (req.url ?? "").split("/");
        res.writeHead(201, { "content-type": "application/json" });
        res.end(
          JSON.stringify({
            protocol: 1,
            path: `/strad/test/mcp/${slug}/static/${variable}`,
            version: "v1",
          }),
        );
      });
    });
    await new Promise<void>((r) => strad.listen(0, "127.0.0.1", r));
    const stradUrl = `http://127.0.0.1:${(strad.address() as { port: number }).port}`;

    const base = testConfig({
      consent: { rejectCooldownSeconds: 0 },
      custody: { stradUrl },
    });
    base.capabilities.custody = {
      enabled: true,
      key: CUSTODY_KEY,
      displayName: "custody-test-mbp",
      clientKeys: {},
    };
    stateDir = tmpState();
    daemon = await startDaemon(base, {
      stateDir,
      prompter: new ScriptedPrompter("allowed"),
      ephemeralPorts: true,
    });
    custody = await connect(daemon.mcpPort, "/custody/mcp", CUSTODY_KEY);
    shell = await connect(daemon.mcpPort, "/shell/mcp", SHELL_KEY);
    for (const [name, c] of [
      ["custody", custody],
      ["shell", shell],
    ] as const) {
      grants[name] = resultJson<{ grant_id: string }>(
        await c.callTool({
          name: "request_control",
          arguments: { purpose: "Keygen test. Nothing else." },
        }),
      ).grant_id;
    }
  }, 30_000);

  afterAll(async () => {
    for (const c of [custody, shell]) await c?.close();
    await daemon?.stop();
    strad?.close();
  });

  interface Generated {
    handle: string;
    shape: { kind: string; length: number };
    key_type: string;
    public_key: string;
    fingerprint: string;
  }
  let generated: Generated;
  let firstBodyLine = "";

  it("is listed, and needs a grant like every custody tool", async () => {
    const { tools } = await custody.listTools();
    expect(tools.map((t) => t.name)).toContain("generate_keypair");
    const res = await custody.callTool({
      name: "generate_keypair",
      arguments: { comment: "x" },
    });
    expect(res.isError).toBe(true);
  });

  it("will not start while a shell command could run through the hold", async () => {
    const started = resultJson<{ command_id: string }>(
      await call(shell, "shell", "run_command", {
        command: "sleep 30",
        wait_seconds: 0,
      }),
    );
    const refused = await call(custody, "custody", "generate_keypair", {
      comment: "strad ssh-example-staging",
    });
    expect(refused.isError).toBe(true);
    expect(resultText(refused)).toMatch(/shell command/);
    await call(shell, "shell", "kill_command", {
      command_id: started.command_id,
    });
    for (let i = 0; i < 50; i++) {
      const st = resultJson<{ status: string }>(
        await call(shell, "shell", "get_command", {
          command_id: started.command_id,
        }),
      );
      if (st.status !== "running") break;
      await new Promise((r) => setTimeout(r, 100));
    }
  });

  it("holds the private key and returns only the public half", async () => {
    expect(await shellWorks()).toBe(true);
    const res = await call(custody, "custody", "generate_keypair", {
      comment: "strad ssh-example-staging",
      label: "staging login key",
    });
    expect(res.isError).toBeFalsy();
    generated = resultJson<Generated>(res);
    expect(generated).toMatchObject({
      handle: expect.stringMatching(/^h_/),
      key_type: "ed25519",
      shape: { kind: "pem" },
      public_key: expect.stringMatching(
        /^ssh-ed25519 AAAA\S+ strad ssh-example-staging$/,
      ),
      fingerprint: expect.stringMatching(/^SHA256:/),
    });
    expect(JSON.stringify(res)).not.toContain("PRIVATE KEY");
    const { handles } = resultJson<{
      handles: { handle: string; state: string; source: string }[];
    }>(await call(custody, "custody", "list_handles"));
    expect(handles[0]).toMatchObject({
      handle: generated.handle,
      state: "held",
      source: `generated ed25519 keypair ${generated.fingerprint}`,
    });
  });

  it("is a held secret: shell is refused until it leaves the vault", async () => {
    expect(await shellWorks()).toBe(false);
  });

  it("deposits the private key straight to strad", async () => {
    const res = await call(custody, "custody", "deposit", {
      handle: generated.handle,
      slug: "ssh-example-staging",
      variable: "SSH_PRIVATE_KEY",
    });
    expect(resultJson(res)).toEqual({
      deposited: true,
      destination: "default",
      path: "/strad/test/mcp/ssh-example-staging/static/SSH_PRIVATE_KEY",
      version: "v1",
    });
    const sent = deposits.at(-1)!;
    expect(sent.url).toBe(
      "/_strad/deposit/ssh-example-staging/SSH_PRIVATE_KEY",
    );
    expect(sent.authorization).toBe(`Bearer ${depositToken(CUSTODY_KEY)}`);
    expect(sent.value).toMatch(/^-----BEGIN OPENSSH PRIVATE KEY-----\n/);
    firstBodyLine = sent.value.split("\n")[1]!;
    if (sshKeygen) {
      const derived = viaSshKeygen(sent.value);
      expect(derived.publicKey).toBe(generated.public_key);
      expect(derived.fingerprint).toBe(generated.fingerprint);
    }
  });

  it("frees the machine once deposited, still filters the private key, and lets the public key through", async () => {
    expect(await shellWorks()).toBe(true);
    const pub = await call(shell, "shell", "run_command", {
      command: `echo '${generated.public_key}'`,
    });
    expect(pub.isError).toBeFalsy();
    expect(resultText(pub)).toContain(generated.public_key);
    const priv = await call(shell, "shell", "run_command", {
      command: `echo ${firstBodyLine}`,
    });
    expect(priv.isError).toBe(true);
    expect(resultText(priv)).toMatch(/arguments contain the secret/);
  });

  it("writes no private key to the audit file", () => {
    const files = readdirSync(stateDir).filter((f) => f.endsWith(".jsonl"));
    expect(files).toContain("audit.jsonl");
    const audit = readFileSync(join(stateDir, "audit.jsonl"), "utf8");
    expect(audit).toContain("generate_keypair");
    expect(audit).not.toContain("PRIVATE KEY");
    expect(audit).not.toContain(firstBodyLine);
  });

  it("drops a generated handle when the grant ends, like a captured one", async () => {
    const res = resultJson<Generated>(
      await call(custody, "custody", "generate_keypair", {
        comment: "discard-me",
      }),
    );
    expect(await shellWorks()).toBe(false);
    await custody.callTool({
      name: "end_control",
      arguments: { grant_id: grants.custody },
    });
    for (let i = 0; i < 50 && !(await shellWorks()); i++)
      await new Promise((r) => setTimeout(r, 100));
    expect(await shellWorks()).toBe(true);
    expect(res.handle).toMatch(/^h_/);
  });
});
