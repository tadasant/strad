/**
 * Vendor a module across an npm-tree boundary — every seam, one mechanism.
 *
 *   npm run vendor:sync                    # write every copy
 *   npm run vendor:sync -- --check         # fail if any copy has drifted
 *   npm run vendor:sync -- --only wire     # one seam
 *   npm run wire:sync -- --check           # the same, through the per-seam alias
 *
 * A supplementary image is its own Docker build context and cannot COPY from the
 * repo root; `servers/bundle/host` and `servers/secrets` are their own npm
 * projects with their own lockfiles and cannot import across the boundary. So
 * these modules have to exist twice. That is vendoring, and vendoring rots unless
 * something checks it, so `test/vendored.sync.test.ts` runs the --check mode of
 * every entry below in CI.
 *
 * Edit the SOURCE, never a copy. Run the sync and commit both halves.
 *
 * Adding a seam is one entry in VENDORED — not a ninth copy of this file. The
 * banner is per-entry because it names the alias an operator will actually type,
 * and it is inside the generated bytes: change it and every copy of that entry
 * has to be rewritten.
 *
 * An entry is one `source` FILE copied to each of `targets`, unless it declares
 * `files:` — then `source` and every `target` are DIRECTORIES and each name in
 * `files` is copied between them. A library that spans four modules is still one
 * id, one alias and one failure; `--only` and the CLI do not know the difference.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

