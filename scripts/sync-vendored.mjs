/**
 * A manifest path, resolved against the repo root rather than the caller's cwd.
 *
 * Exported so a test reads the same file this renders from. Two resolutions of
 * one `source` string is two opinions about which file the seam is about.
 */
export function repoPath(relative) {
  return join(root, relative);
}

/**
 * Every copy `entry` owns, as a `{ source, target }` pair of repo-relative paths.
 *
 * One pair per target for a single-file entry; one per target per `files` name
 * otherwise. Everything downstream — the check, the write, the counts, the test
 * that asserts no stamped file is unclaimed — reads copies from here, so a
 * multi-file seam is a longer list rather than a second code path.
 */
export function copies(entry) {
  return entry.targets.flatMap((target) =>
    entry.files
      ? entry.files.map((name) => ({
          source: `${entry.source}/${name}`,
          target: `${target}/${name}`,
        }))
      : [{ source: entry.source, target }],
  );
}

/** The exact bytes the copy of `source` should hold. */
export function rendered(entry, source = entry.source) {
  return entry.banner + readFileSync(repoPath(source), "utf8");
}

/** The paths of `entry` whose vendored copy is missing or stale. */
export function drifted(entry) {
  return copies(entry)
    .filter(({ source, target }) => {
      const path = repoPath(target);
      if (!existsSync(path)) return true;
      return readFileSync(path, "utf8") !== rendered(entry, source);
    })
    .map(({ target }) => target);
}

/**
 * The entries `--only` selects, or all of them.
 *
 * An unknown id THROWS rather than selecting nothing. A `--check` over an empty
 * selection exits 0, which is indistinguishable from a clean tree — the exact
 * fail-open this whole mechanism exists to close.
 */
export function select(only) {
  if (only === null || only === undefined) return VENDORED;
  const entry = VENDORED.find((candidate) => candidate.id === only);
  if (!entry) {
    throw new Error(
      `unknown --only id "${only}". Known ids: ${VENDORED.map((e) => e.id).join(", ")}.`,
    );
  }
  return [entry];
}

const USAGE = "usage: sync-vendored.mjs [--check] [--only <id>]";

/**
 * `--check` and `--only <id>`, in either order.
 *
 * An argument this does not understand THROWS. Ignoring one would make `--chek`
 * fall through to the write path and rewrite every copy on behalf of someone who
 * asked to verify them, and `--only=wire --check` silently check all eight.
 */
export function parseArgs(argv) {
  let check = false;
  let only = null;

  for (let at = 0; at < argv.length; at++) {
    const arg = argv[at];
    if (arg === "--check") {
      check = true;
    } else if (arg === "--only") {
      only = argv[++at];
      if (!only || only.startsWith("--")) {
        throw new Error(`--only needs an id, e.g. \`--only wire\`. ${USAGE}`);
      }
    } else if (arg.startsWith("--only=")) {
      only = arg.slice("--only=".length);
      if (!only) {
        throw new Error(`--only needs an id, e.g. \`--only wire\`. ${USAGE}`);
      }
    } else {
      throw new Error(`unknown argument "${arg}". ${USAGE}`);
    }
  }

  return { check, only };
}

const plural = (n) => (n === 1 ? "copy" : "copies");

function main(argv = process.argv.slice(2)) {
  let entries;
  let check;
  try {
    const args = parseArgs(argv);
    check = args.check;
    entries = select(args.only);
  } catch (error) {
    console.error(`::error::${error.message}`);
    process.exit(2);
  }

  if (check) {
    let clean = true;
    for (const entry of entries) {
      const stale = drifted(entry);
      if (stale.length === 0) {
        const count = copies(entry).length;
        console.log(`${entry.id}: ${count} vendored ${plural(count)} in sync.`);
        continue;
      }
      clean = false;
      console.error(
        `::error::${entry.label} is out of sync in:\n  ${stale.join("\n  ")}\n` +
          `Run \`npm run vendor:sync -- --only ${entry.id}\` and commit the result.`,
      );
    }
    if (!clean) process.exit(1);
    return;
  }

  for (const entry of entries) {
    const pairs = copies(entry);
    for (const { source, target } of pairs) {
      const path = repoPath(target);
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, rendered(entry, source));
    }
    console.log(`${entry.id}: synced ${pairs.length} ${plural(pairs.length)}.`);
  }
}

// Only run when invoked directly, so the test can import VENDORED/drifted().
if (process.argv[1] && process.argv[1].endsWith("sync-vendored.mjs")) main();
